const now = new Date();

/** 相对今天生成日期，保证“本周 / 上周”演示永远有数据 */
function daysAgo(days: number, hour = 10): string {
  const d = new Date(now);
  d.setDate(d.getDate() - days);
  d.setHours(hour, 12, 0, 0);
  return d.toISOString();
}

